@app.on_event("startup")
def warm_up_diffusion_model():
    """
    Load the trained DDPM once at startup.

    This avoids loading PyTorch lazily inside the generation worker.
    """

    if _image_backend() != "local":
        print(
            "[startup] Cloud image backend enabled; skipping local DDPM warm-up.",
            flush=True,
        )
        return

    try:

        print(
            "[startup] Warming up diffusion model...",
            flush=True,
        )

        image_generation.load_model()

        print(
            "[startup] Diffusion model ready.",
            flush=True,
        )

    except FileNotFoundError as exc:

        print(
            "[startup] Diffusion checkpoint not found.",
            flush=True,
        )

        print(
            f"[startup] {exc}",
            flush=True,
        )


