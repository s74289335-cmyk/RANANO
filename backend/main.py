@app.post(
    "/api/generate-image/start"
)
def generate_image_start():

    job_id = _make_job()

    def run():

        try:

            backend = _image_backend()

            if backend == "cloud":
                _update_job(job_id, 10, "generating with hosted open model")
                img = cloud_image.generate_text_to_image(
                    "A high-quality creative image",
                )
                _update_job(job_id, 92, "saving cloud-generated image")
                enhancement_name = "Hosted open-model generation"
                generation_name = os.getenv(
                    "HF_GENERATION_MODEL",
                    "black-forest-labs/FLUX.1-schnell",
                )
            else:
                _update_job(job_id, 1, "generating with RANANO DDPM")

                def progress_cb(step, total):
                    overall = int((float(step) / float(total)) * 80) if total else 1
                    _update_job(job_id, overall, "generating with RANANO DDPM")

                img = image_generation.generate_image(progress_callback=progress_cb)
                _update_job(job_id, 82, "enhancing with ESRGAN")
                img = super_resolution.enhance_generated_image(img)
                _update_job(job_id, 97, "saving final image")
                enhancement_name = "TensorFlow Hub ESRGAN x4"
                generation_name = "RANANO trained DDPM"

            print(
                f"[RANANO] Generation backend {backend} complete: "
                f"{img.size[0]}x{img.size[1]}",
                flush=True,
            )

            # --------------------------------------------------------------
            # SAVE: 97 -> 100
            # --------------------------------------------------------------

            url = _save_and_url(
                img,
                "generated",
            )

            print(
                f"[RANANO] Generation complete: {url}",
                flush=True,
            )

            _finish_job(
                job_id,
                result={
                    "image_url": url,
                    "generation_size": list(img.size),
                    "final_size": list(img.size),
                    "enhancement": enhancement_name,
                    "generation_model": generation_name,
                    "backend": backend,
                },
            )

        except Exception as exc:

            print(
                "[RANANO] Random generation failed:",
                repr(exc),
                flush=True,
            )

            _finish_job(
                job_id,
                error=str(exc),
            )

    _generation_executor.submit(
        run
    )

    return {
        "job_id": job_id
    }


