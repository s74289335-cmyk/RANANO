# VOICE TRANSCRIPTION (Groq Whisper)
# ===========================================================================

@app.post("/api/transcribe-audio")
async def transcribe_audio(file: UploadFile = File(...)):
    """
    Transcribe browser-recorded audio with Groq Whisper.
    This route does not store uploaded audio on disk.
    """
    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        raise HTTPException(status_code=503, detail="GROQ_API_KEY is not configured.")

    allowed_types = {
        "audio/webm", "audio/webm;codecs=opus", "audio/ogg",
        "audio/mp4", "audio/mpeg", "audio/wav", "audio/x-wav",
        "audio/mp3", "audio/m4a", "audio/aac"
    }
    content_type = (file.content_type or "").lower()
    if content_type and not any(content_type.startswith(t.split(";")[0]) for t in allowed_types):
        raise HTTPException(status_code=400, detail=f"Unsupported audio content type: {content_type}")

    audio_bytes = await file.read()
    if not audio_bytes:
        raise HTTPException(status_code=400, detail="No audio was recorded.")
    if len(audio_bytes) > 25 * 1024 * 1024:
        raise HTTPException(status_code=413, detail="Audio is too large (maximum 25 MB).")

    import requests
    suffix = ".webm"
    if "mp4" in content_type or "m4a" in content_type:
        suffix = ".mp4"
    elif "wav" in content_type:
        suffix = ".wav"
    elif "ogg" in content_type:
        suffix = ".ogg"
    elif "mpeg" in content_type or "mp3" in content_type:
        suffix = ".mp3"

    try:
        response = requests.post(
            "https://api.groq.com/openai/v1/audio/transcriptions",
            headers={"Authorization": f"Bearer {api_key}"},
            files={"file": (f"ranano-audio{suffix}", audio_bytes, content_type or "audio/webm")},
            data={"model": "whisper-large-v3-turbo", "language": "en", "response_format": "json"},
            timeout=90,
        )
    except requests.RequestException as exc:
        raise HTTPException(status_code=502, detail=f"Speech transcription request failed: {type(exc).__name__}")

    if not response.ok:
        detail = response.text[:500]
        raise HTTPException(status_code=response.status_code if response.status_code < 500 else 502,
                         detail=f"Groq transcription failed ({response.status_code}): {detail}")

    try:
        transcript = (response.json().get("text") or "").strip()
    except ValueError:
        raise HTTPException(status_code=502, detail="Groq returned an invalid transcription response.")

    if not transcript:
        raise HTTPException(status_code=422, detail="No speech was detected. Try speaking a little louder or longer.")
    return {"text": transcript}

