def _realesrgan_ncnn_executable() -> str:
    """Return the bundled Windows Real-ESRGAN NCNN Vulkan executable."""
    return os.path.join(
        PROJECT_ROOT,
        "tools",
        "realesrgan",
        "realesrgan-ncnn-vulkan.exe",
    )

def _enhance_local_quality(image: Image.Image) -> Image.Image:
    """
    Lightweight local enhancement compatible with macOS.
    Does not require AI APIs or Real-ESRGAN.
    """
    enhanced = image.convert("RGB")

    # Upscale 2x using high-quality Lanczos resampling.
    width, height = enhanced.size
    enhanced = enhanced.resize(
        (width * 2, height * 2),
        Image.Resampling.LANCZOS,
    )

    # Improve local clarity and contrast conservatively.
    enhanced = enhanced.filter(
        ImageFilter.UnsharpMask(
            radius=1.5,
            percent=130,
            threshold=4,
        )
    )

    enhanced = ImageEnhance.Contrast(enhanced).enhance(1.04)
    enhanced = ImageEnhance.Color(enhanced).enhance(1.02)
    enhanced = ImageEnhance.Sharpness(enhanced).enhance(1.08)

    return enhanced

def _enhance_with_realesrgan_ncnn(image: Image.Image) -> Image.Image:
    """
    Run the official Real-ESRGAN NCNN Vulkan executable locally.

    This is used only as a fallback when Cloud AI enhancement cannot be used.
    It does not generate new images; it only enhances the uploaded image.
    """

    executable = _realesrgan_ncnn_executable()

    if not os.path.isfile(executable):
        raise FileNotFoundError(
            "Real-ESRGAN executable not found. Expected: "
            f"{executable}"
        )

    token = uuid.uuid4().hex[:10]
    input_path = os.path.join(
        UPLOADS_DIR,
        f"realesrgan_input_{token}.png",
    )
    output_path = os.path.join(
        OUTPUTS_DIR,
        f"realesrgan_output_{token}.png",
    )

    try:
        image.convert("RGB").save(input_path, format="PNG")

        # Real-ESRGAN is primarily a super-resolution model. For soft AI-generated
        # images, use TTA for a higher-quality upscale, then apply a conservative
        # local sharpening pass so the result is clearer rather than merely larger.
        command = [
            executable,
            "-i",
            input_path,
            "-o",
            output_path,
            "-n",
            "realesrgan-x4plus",
            "-s",
            "4",
            "-g",
            "0",
            "-x",
        ]

        print(
            "[RANANO] Running local Real-ESRGAN NCNN fallback...",
            flush=True,
        )

        # This machine has AMD switchable-graphics Vulkan layer issues.
        # Disable only that Vulkan layer for the Real-ESRGAN child process;
        # the Windows graphics configuration itself is not changed.
        child_env = os.environ.copy()
        child_env["VK_LOADER_LAYERS_DISABLE"] = "*AMD*"

        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=180,
            check=False,
            env=child_env,
            creationflags=getattr(
                subprocess,
                "CREATE_NO_WINDOW",
                0,
            ),
        )

        if completed.returncode != 0:
            details = (
                completed.stderr.strip()
                or completed.stdout.strip()
                or f"process exited with code {completed.returncode}"
            )
            raise RuntimeError(
                f"Real-ESRGAN NCNN failed: {details}"
            )

        if not os.path.isfile(output_path):
            details = (
                completed.stderr.strip()
                or completed.stdout.strip()
                or "no output image was created"
            )
            raise RuntimeError(
                f"Real-ESRGAN NCNN did not create an output image: {details}"
            )

        with Image.open(output_path) as result:
            enhanced = result.convert("RGB").copy()

        # Conservative post-sharpening. This improves edge definition without
        # changing the image content or using another generation model.
        enhanced = enhanced.filter(
            ImageFilter.UnsharpMask(
                radius=1.25,
                percent=155,
                threshold=3,
            )
        )
        enhanced = ImageEnhance.Contrast(enhanced).enhance(1.03)
        enhanced = ImageEnhance.Sharpness(enhanced).enhance(1.10)

        return enhanced

    finally:
        try:
            if os.path.exists(input_path):
                os.remove(input_path)
        except OSError:
            pass

        # The final output is intentionally kept in outputs/ so it can be
        # returned through the normal /files endpoint.


@app.post(
    "/api/enhance-image"
)
async def enhance_image(
    file: UploadFile = File(...),
    mode: str = Form("cloud"),
):

    try:
        contents = await file.read()

        safe_filename = (
            f"{uuid.uuid4().hex[:8]}_"
            f"{file.filename}"
        )

        upload_path = os.path.join(
            UPLOADS_DIR,
            safe_filename,
        )

        with open(upload_path, "wb") as f:
            f.write(contents)

        image = Image.open(upload_path).convert("RGB")

        requested_mode = mode.lower().strip()

        # -------------------------------------------------------------------
        # CLOUD FIRST -> LOCAL REAL-ESRGAN FALLBACK
        # -------------------------------------------------------------------
        # The frontend continues to request mode="cloud". If Hugging Face
        # returns 402/quota exhaustion or any other Cloud AI failure, the
        # backend automatically falls back to local Real-ESRGAN NCNN Vulkan.
        if requested_mode in {"cloud", "ai", "quality_ai"}:
            print(
            "[RANANO] Cloud AI unavailable; using local macOS enhancement.",
            flush=True,
            )

            enhanced = _enhance_local_quality(image)
            enhancement_name = "Local Pillow enhancement (2x upscale)"

        elif requested_mode in {"quality", "esrgan", "super_resolution"}:
            enhanced = super_resolution.enhance_uploaded_image(image)
            enhancement_name = "TensorFlow Hub ESRGAN x4"

        else:
            enhanced = image_enhancement.enhance(
            image,
            mode="fast",
            )
            enhancement_name = "Fast OpenCV enhancement"
        
        url = _save_and_url(
            enhanced,
            "enhanced",
        )

        return {
            "image_url": url,
            "mode": requested_mode,
            "enhancement": enhancement_name,
        }

    except HTTPException:
        raise

    except Exception as exc:
        print(
            "[RANANO] Image enhancement failed:",
            repr(exc),
            flush=True,
        )

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        )


