class ChatTurn(
    BaseModel
):

    role: str
    content: str


class ChatRequest(
    BaseModel
):

    message: str
    history: list[ChatTurn] = []
    tool: str = "RANANO Studio"


@app.post(
    "/api/chat"
)
def chat(
    req: ChatRequest,
):

    intent_result = {
        "intent": None,
        "confidence": 0.0,
    }

    # --------------------------------------------------------------
    # Intent classifier
    # --------------------------------------------------------------

    try:

        intent_result = (
            voice_assistant.classify_intent(
                req.message
            )
        )

    except Exception as exc:

        print(
            f"[chat] intent classifier unavailable: {exc}",
            flush=True,
        )

    # --------------------------------------------------------------
    # Conversation history
    # --------------------------------------------------------------

    history_dicts = [
        {
            "role": turn.role,
            "content": turn.content,
        }
        for turn in req.history
    ]

    # --------------------------------------------------------------
    # Groq conversational assistant
    # --------------------------------------------------------------

    reply = (
        voice_assistant.chat_with_groq(
            message=req.message,
            history=history_dicts,
            detected_intent=(
                intent_result.get(
                    "intent"
                )
            ),
            tool_context=req.tool,
        )
    )

    return {
        "reply": reply,
        "intent": (
            intent_result.get(
                "intent"
            )
        ),
        "confidence": (
            intent_result.get(
                "confidence",
                0.0,
            )
        ),
    }